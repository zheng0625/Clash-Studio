const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true}),results=[],errors=[],requests=[]
 try{
  const page=await browser.newPage({viewport:{width:1500,height:1100}})
  page.on('pageerror',error=>errors.push(error.message))
  page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/'))requests.push(request.url())})
  await page.goto('http://127.0.0.1:5181/ui-android-components.html')
  const entries=await page.evaluate(async()=>{const m=await import('/src/component-lab/android-catalogue.ts');return m.androidCatalogue})
  for(const entry of entries){
   try{
    await page.goto('http://127.0.0.1:5181/ui-android-components.html?component='+entry.id)
    const frame=page.frameLocator('iframe[title="客户端原位预览"]')
    const target=frame.locator(entry.selector).first()
    await target.locator('xpath=self::*[contains(@class,"lab-target")]').waitFor({timeout:6500})
    const dimensions=await target.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height])
    assert.ok(dimensions[0]>0&&dimensions[1]>0)
    await page.waitForFunction(()=>!document.querySelector('[aria-label="中心 X"]').disabled)
    const centerX=page.getByRole('spinbutton',{name:'中心 X',exact:true})
    assert.equal(await centerX.isEnabled(),true)
    const previous=Number(await centerX.inputValue())
    await centerX.fill(String(previous+2))
    assert.ok(Math.abs(Number(await centerX.inputValue())-previous-2)<.15)
    const centerY=page.getByRole('spinbutton',{name:'中心 Y',exact:true})
    const previousY=Number(await centerY.inputValue())
    await centerY.fill(String(previousY+2))
    const measured=await target.evaluate(e=>{const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})
    assert.ok(Math.abs(measured.x-previous-2)<.15)
    assert.ok(Math.abs(measured.y-previousY-2)<.15)
    await page.getByRole('button',{name:'重置当前元素',exact:true}).click()
    results.push({id:entry.id,page:entry.page,ok:true,centerEditing:true})
   }catch(error){results.push({id:entry.id,page:entry.page,ok:false,error:error.message.slice(0,180)});console.log('FAIL',entry.id)}
  }
  // Phone, landscape and tablet presets must change the actual iframe viewport.
  await page.goto('http://127.0.0.1:5181/ui-android-components.html?component=android-navigation')
  await page.waitForFunction(()=>!document.querySelector('[aria-label="中心 X"]').disabled)
  for(const [width,height,tier] of [[360,780,'compact'],[393,873,'compact'],[430,932,'compact'],[780,412,'compact'],[1024,768,'tablet']]){
   await page.locator('.lab-toolbar select').nth(2).selectOption(String(width))
   await page.waitForFunction(([w,h,tier])=>{const win=document.querySelector('iframe').contentWindow;return win.innerWidth===w&&win.innerHeight===h&&win.document.documentElement.dataset.mobileTier===tier},[width,height,tier])
   const state=await page.frameLocator('iframe').locator('html').evaluate(e=>({tier:e.dataset.mobileTier,desktop:'__TAURI_INTERNALS__' in window,overflow:document.documentElement.scrollWidth>innerWidth}))
   assert.equal(state.tier,tier);assert.equal(state.desktop,false);assert.equal(state.overflow,false)
  }
  await page.getByRole('spinbutton',{name:'自定义窗口宽度',exact:true}).fill('417')
  await page.getByRole('spinbutton',{name:'窗口高度',exact:true}).fill('887')
  await page.getByRole('spinbutton',{name:'X 位移',exact:true}).fill('5')
  const saved=await page.evaluate(()=>({android:localStorage.getItem('clash-android-component-layout-v1'),desktop:localStorage.getItem('clash-component-layout-v1')}))
  assert.ok(saved.android.includes('left'));assert.equal(saved.desktop,null)
  await page.getByRole('button',{name:'确认满意并锁定',exact:true}).click()
  assert.equal(await page.getByRole('spinbutton',{name:'中心 X',exact:true}).isDisabled(),true)
  await page.reload();await page.waitForFunction(()=>document.querySelector('iframe')?.contentDocument?.querySelector('.lab-target'))
  assert.equal(await page.getByRole('button',{name:'解锁，继续打磨',exact:true}).count(),1)
  assert.equal(await page.evaluate(()=>localStorage.getItem('clash-studio-component-reviews-v2')),null)
  await page.getByRole('button',{name:'解锁，继续打磨',exact:true}).click()
  await page.getByRole('button',{name:'重置当前元素',exact:true}).click()
  await page.locator('.lab-toolbar select').nth(2).selectOption('393')
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'导出本页元素坐标 CSV',exact:true}).click();const csv=await downloadPromise;await csv.saveAs('test-output/android-element-coordinates.csv')
  assert.ok(fs.readFileSync('test-output/android-element-coordinates.csv','utf8').includes('中心 X'))
  await page.screenshot({path:'test-output/android-component-workshop.png',fullPage:true})
  fs.mkdirSync('test-output',{recursive:true})
  fs.writeFileSync('test-output/android-component-catalogue-report.json',JSON.stringify({results,presets:true,arbitraryViewport:true,storageIsolation:true,lockPersistence:true,coordinateExport:true,errors,apiRequests:requests},null,2))
  console.log(JSON.stringify({targets:results.length,pages:[...new Set(results.map(r=>r.page))],failures:results.filter(r=>!r.ok),errors,apiRequests:requests.length}))
  assert.deepEqual(results.filter(r=>!r.ok),[]);assert.deepEqual(errors,[]);assert.deepEqual(requests,[])
 }finally{await browser.close()}
})().catch(error=>{console.error(error.message);process.exitCode=1})
