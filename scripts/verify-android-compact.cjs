const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true}),errors=[],requests=[]
 try{
  const page=await browser.newPage({viewport:{width:1450,height:1100}})
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))requests.push(r.url())})
  const preset=JSON.parse(fs.readFileSync('frontend/src/component-lab/presets/android-user-layout.json','utf8'))
  await page.addInitScript(rules=>{if(!localStorage.getItem('test-seeded')){localStorage.setItem('clash-android-component-layout-v1',JSON.stringify(rules));localStorage.setItem('test-seeded','1')}},preset.rules)
  async function visit(id,android=true){await page.goto('http://127.0.0.1:5181/'+(android?'ui-android-components.html':'ui-components.html')+'?component='+id);await page.waitForFunction(()=>!document.querySelector('[aria-label="中心 X"]').disabled);return page.frameLocator('iframe')}
  let frame=await visit('usage')
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('clash-android-component-layout-v1')).length),0)
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('clash-android-component-layout-v1-before-compact-v1')).length),15)
  assert.equal(await frame.locator('header.desk-topbar').count(),0)
  assert.deepEqual(await frame.locator('.profile-card').evaluate(e=>[e.offsetWidth,e.offsetHeight]),[342,220])
  assert.deepEqual(await frame.locator('.add-profile').evaluate(e=>[e.offsetWidth,e.offsetHeight]),[342,220])
  const overlap=await frame.locator('.shell-brand').evaluate(e=>e.getBoundingClientRect().bottom>document.querySelector('.desk-page-heading').getBoundingClientRect().top)
  assert.equal(overlap,false)
  assert.equal(await frame.locator('.profile-card').evaluate(e=>e.scrollHeight>e.clientHeight),false)
  await page.locator('.lab-context-canvas').screenshot({path:'test-output/android-compact-card-final.png'})
  // Delete is a persistent display rule: Vue keeps ownership of the DOM and business data.
  await page.getByRole('button',{name:'删除元素',exact:true}).click()
  assert.equal(await frame.locator('.profile-card').isVisible(),false)
  assert.equal(await page.getByRole('button',{name:'恢复元素',exact:true}).count(),1)
  await page.getByRole('button',{name:'撤销',exact:true}).click()
  assert.equal(await frame.locator('.profile-card').isVisible(),true)
  await page.getByRole('button',{name:'重做',exact:true}).click()
  assert.equal(await frame.locator('.profile-card').isVisible(),false)
  const jsonPromise=page.waitForEvent('download');await page.getByRole('button',{name:'导出布局 JSON',exact:true}).click();await (await jsonPromise).saveAs('test-output/deleted-layout.json')
  assert.ok(JSON.parse(fs.readFileSync('test-output/deleted-layout.json','utf8')).rules.some(r=>r.styles.display==='none'))
  const cssPromise=page.waitForEvent('download');await page.getByRole('button',{name:'导出正式页面 CSS',exact:true}).click();await (await cssPromise).saveAs('test-output/deleted-layout.css')
  assert.ok(fs.readFileSync('test-output/deleted-layout.css','utf8').includes('display: none !important'))
  await page.reload();await page.getByRole('button',{name:'恢复元素',exact:true}).waitFor()
  assert.equal(await frame.locator('.profile-card').isVisible(),false)
  await page.getByRole('button',{name:'恢复元素',exact:true}).click()
  assert.equal(await frame.locator('.profile-card').isVisible(),true)
  await frame.locator('.profile-card h2').click();await frame.locator('body').press('Delete')
  assert.equal(await frame.locator('.profile-card h2').isVisible(),false)
  await page.getByRole('button',{name:'恢复元素',exact:true}).click()
  await page.getByRole('button',{name:'确认满意并锁定',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'删除元素',exact:true}).isDisabled(),true)
  await page.getByRole('button',{name:'解锁，继续打磨',exact:true}).click()
  for(const [id,height] of [['dialog-dns',360],['dialog-ipv6',360],['routing-create',441],['routing-edit',441],['subscription-import',472]]){
   frame=await visit(id)
   assert.deepEqual(await frame.locator('dialog[open]').evaluate(e=>[e.offsetWidth,e.offsetHeight]),[377,height])
   assert.equal(await frame.locator('.app-dialog-body').filter({visible:true}).count(),1)
   await page.locator('.lab-context-canvas').screenshot({path:'test-output/android-compact-final-'+id+'.png'})
   // Short viewports (keyboard / landscape) keep header/footer visible and body scrollable.
   await page.getByRole('spinbutton',{name:'自定义窗口宽度',exact:true}).fill('360')
   await page.getByRole('spinbutton',{name:'窗口高度',exact:true}).fill('320')
   const bounds=await frame.locator('dialog[open]').evaluate(e=>{const r=e.getBoundingClientRect(),body=e.querySelector('.app-dialog-body'),footer=e.querySelector('footer').getBoundingClientRect();return {x:r.x,right:r.right,y:r.y,bottom:r.bottom,footer:footer.bottom,scroll:getComputedStyle(body).overflowY}})
   assert.ok(bounds.x>=0&&bounds.right<=360&&bounds.y>=0&&bounds.bottom<=320&&bounds.footer<=320)
   assert.equal(bounds.scroll,'auto')
  }
  frame=await visit('shell-topbar',false)
  assert.equal(await frame.locator('header.desk-topbar').count(),1)
  await page.getByRole('button',{name:'删除元素',exact:true}).click()
  assert.equal(await frame.locator('header.desk-topbar').isVisible(),false)
  await page.getByRole('button',{name:'恢复元素',exact:true}).click()
  assert.equal(await frame.locator('header.desk-topbar').isVisible(),true)
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[])
  const report={adoptedRules:15,card:[342,220],dialogs:true,shortViewport:true,topbarRemovedOnAndroid:true,desktopTopbarPreserved:true,deletion:true,keyboardDelete:true,undoRedo:true,restoreAfterReload:true,export:true,lockProtection:true,errors,requests}
  fs.writeFileSync('test-output/android-compact-verification.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report))
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
