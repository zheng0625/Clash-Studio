const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
  const browser=await chromium.launch({headless:true,channel:'msedge'})
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    await page.goto('http://127.0.0.1:5181/ui-components.html?component=usage')
    const frame=page.frameLocator('iframe[title="客户端原位预览"]')
    const title=frame.locator('.profile-card h2')
    await title.waitFor()
    await page.waitForFunction(()=>!document.querySelector('[aria-label="中心 X"]').disabled)
    await page.getByRole('spinbutton',{name:'自定义窗口宽度',exact:true}).fill('1173')
    await page.getByRole('spinbutton',{name:'窗口高度',exact:true}).fill('777')
    assert.deepEqual(await frame.locator('body').evaluate(()=>[innerWidth,innerHeight]),[1173,777])
    await title.scrollIntoViewIfNeeded()
    let box=await title.boundingBox()
    const board=await page.locator('iframe').boundingBox()
    const scale=board.width/1173
    const ruler=page.getByRole('img',{name:'水平像素刻度尺',exact:true})
    const rulerBox=await ruler.boundingBox()
    const tick=await ruler.locator('g[data-pixel="100"] line').boundingBox()
    assert.ok(Math.abs(tick.x-rulerBox.x-100*scale)<1)
    await page.getByRole('checkbox',{name:'显示 10 px 网格',exact:true}).check()
    assert.equal(await page.locator('.ruler-grid').count(),1)
    await page.mouse.move(box.x+20,box.y+box.height/2)
    await page.mouse.down()
    await page.mouse.move(box.x+60,box.y+box.height/2+20,{steps:8})
    await page.mouse.up()
    let offset=await title.evaluate(e=>[parseFloat(getComputedStyle(e).left),parseFloat(getComputedStyle(e).top)])
    assert.ok(Math.abs(offset[0]-40/scale)<=2,JSON.stringify({offset,scale}))
    assert.ok(Math.abs(offset[1]-20/scale)<=2)
    const selectedBox=await title.boundingBox(),guide=await page.locator('.guide-x').first().boundingBox()
    assert.ok(Math.abs(selectedBox.x-guide.x)<1)
    const center=await title.evaluate(e=>{const r=e.getBoundingClientRect();return {x:Math.round((r.left+r.width/2)*10)/10,y:Math.round((r.top+r.height/2)*10)/10}})
    assert.equal(Number(await page.getByRole('spinbutton',{name:'中心 X',exact:true}).inputValue()),center.x)
    assert.equal(Number(await page.getByRole('spinbutton',{name:'中心 Y',exact:true}).inputValue()),center.y)
    await page.getByRole('spinbutton',{name:'中心 X',exact:true}).fill(String(center.x+12.5))
    await page.getByRole('spinbutton',{name:'中心 Y',exact:true}).fill(String(center.y+7.5))
    const positioned=await title.evaluate(e=>{const r=e.getBoundingClientRect();return [r.left+r.width/2,r.top+r.height/2]})
    assert.ok(Math.abs(positioned[0]-center.x-12.5)<.12)
    assert.ok(Math.abs(positioned[1]-center.y-7.5)<.12)
    const centerGuide=page.getByLabel('选中元素中心点',{exact:true})
    assert.ok(Math.abs(Number(await centerGuide.getAttribute('data-center-x'))-positioned[0])<.12)
    const csvDownload=page.waitForEvent('download')
    await page.getByRole('button',{name:'导出本页元素坐标 CSV',exact:true}).click()
    const csv=fs.readFileSync(await (await csvDownload).path(),'utf8')
    assert.match(csv,/中心 X/);assert.match(csv,/中心 Y/);assert.ok(csv.split('\r\n').length>20)
    await page.getByRole('spinbutton',{name:'元素宽度',exact:true}).fill('233')
    await page.getByRole('spinbutton',{name:'元素高度',exact:true}).fill('53')
    assert.deepEqual(await title.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height]),[233,53])
    await title.scrollIntoViewIfNeeded()
    const handle=frame.getByRole('button',{name:'调整元素尺寸 se',exact:true})
    box=await handle.boundingBox()
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
    await page.mouse.down();await page.mouse.move(box.x+box.width/2+24,box.y+box.height/2+16,{steps:6});await page.mouse.up()
    const resized=await title.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height])
    assert.ok(Math.abs(resized[0]-(233+24/scale))<=2,JSON.stringify(resized))
    await page.getByRole('button',{name:'撤销',exact:true}).click()
    assert.deepEqual(await title.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height]),[233,53])
    await page.getByRole('button',{name:'重做',exact:true}).click()
    assert.deepEqual(await title.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height]),resized)
    const jsonDownload=page.waitForEvent('download')
    await page.getByRole('button',{name:'导出布局 JSON',exact:true}).click()
    const jsonPath=await (await jsonDownload).path()
    const project=JSON.parse(fs.readFileSync(jsonPath,'utf8'))
    assert.deepEqual(project.viewport,{width:1173,height:777})
    assert.ok(project.rules.length)
    const cssDownload=page.waitForEvent('download')
    await page.getByRole('button',{name:'导出正式页面 CSS',exact:true}).click()
    const css=fs.readFileSync(await (await cssDownload).path(),'utf8')
    assert.match(css,/\.desk\[data-ui-page="subscriptions"\]/)
    await page.reload()
    await frame.locator('.profile-card.lab-target').waitFor()
    assert.deepEqual(await title.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height]),resized)
    await title.click()
    await page.getByRole('button',{name:'重置当前元素',exact:true}).click()
    assert.equal(await title.evaluate(e=>getComputedStyle(e).left),'auto')
    await page.locator('.lab-layout-export input[type=file]').setInputFiles(jsonPath)
    assert.deepEqual(await title.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height]),resized)
    // Drag the viewport grip while fitting is disabled, so its physical size grows.
    await page.getByRole('checkbox',{name:'缩放适应',exact:true}).uncheck()
    const grip=page.getByRole('button',{name:'拖动调整画布尺寸',exact:true})
    await grip.scrollIntoViewIfNeeded();box=await grip.boundingBox()
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down()
    await page.mouse.move(box.x+box.width/2+35,box.y+box.height/2+25,{steps:5});await page.mouse.up()
    assert.deepEqual(await frame.locator('body').evaluate(()=>[innerWidth,innerHeight]),[1208,802])
    // Exercise the same editor in the non-iframe component surface.
    await page.getByRole('combobox',{name:'查看方式'}).selectOption('isolated')
    const solo=page.locator('.lab-preview .profile-card h2')
    await solo.click()
    await page.getByRole('spinbutton',{name:'X 位移',exact:true}).fill('-17')
    assert.equal(await solo.evaluate(e=>getComputedStyle(e).left),'-17px')
    const inline=page.locator('.lab-preview .usage-numbers b').first()
    await inline.click()
    await page.getByRole('spinbutton',{name:'元素宽度',exact:true}).fill('91')
    await page.getByRole('spinbutton',{name:'元素高度',exact:true}).fill('31')
    assert.deepEqual(await inline.evaluate(e=>[e.getBoundingClientRect().width,e.getBoundingClientRect().height]),[91,31])
    await page.getByRole('button',{name:'交互预览',exact:true}).click()
    assert.equal(await page.locator('#component-layout-selection').isVisible(),false)
    assert.deepEqual(errors,[])
    assert.equal(await page.getByRole('img',{name:'垂直像素刻度尺',exact:true}).count(),1)
    console.log(JSON.stringify({arbitraryViewport:[1173,777],scaledRulers:true,elementGuides:true,centerCoordinates:true,centerPositioning:true,coordinateExport:true,grid:true,scaledDrag:true,resizeHandles:true,numericGeometry:true,viewportGrip:true,undoRedo:true,reloadPersistence:true,reset:true,importExport:true,isolatedEditing:true,errors}))
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
