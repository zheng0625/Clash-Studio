const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true}),errors=[],requests=[],states=[]
 try{
  const page=await browser.newPage({viewport:{width:1500,height:1200}})
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))requests.push(r.url())})
  const preset=JSON.parse(fs.readFileSync('frontend/src/component-lab/presets/android-state-layout.json','utf8'))
  await page.addInitScript(rules=>{if(!localStorage.getItem('states-seeded')){localStorage.setItem('clash-android-component-layout-v1',JSON.stringify(rules));localStorage.setItem('states-seeded','1')}},preset.rules)
  async function visit(id,scene='正常'){
   await page.goto('http://127.0.0.1:5181/ui-android-components.html?component='+id)
   if(scene!=='正常')await page.locator('.lab-toolbar select').nth(1).selectOption(scene)
   await page.waitForFunction(scene=>new URLSearchParams(document.querySelector('iframe')?.contentWindow?.location.search).get('scene')===scene,scene)
   await page.frameLocator('iframe').locator('.lab-target').waitFor()
   await page.waitForFunction(()=>!document.querySelector('[aria-label="中心 X"]').disabled)
   return page.frameLocator('iframe')
  }
  for(const scene of ['待启动','运行中','应用中','待应用','应用失败','未导入','全局模式','直连模式']){
   const f=await visit('kernel',scene)
   if(scene==='应用失败')await f.locator('.kernel-actions button').first().filter({hasText:'重试应用'}).waitFor()
   if(scene==='应用中')await f.locator('.kernel-actions button').first().filter({hasText:'正在应用'}).waitFor()
   const state=await f.locator('.kernel-launch-card').evaluate(e=>{const r=e.getBoundingClientRect();return {width:r.width,height:r.height,buttons:[...e.querySelectorAll('.routing-segment button')].map(b=>{const s=getComputedStyle(b);return [b.offsetWidth,b.offsetHeight,s.letterSpacing,s.whiteSpace]}),help:getComputedStyle(e.querySelector('.android-network-help')).display}})
   assert.equal(state.width,342);assert.ok(state.height>=182)
   for(const button of state.buttons)assert.deepEqual(button,[77,40,'4.6px','nowrap'])
   assert.equal(state.help,'none');states.push(scene)
  }
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('clash-android-component-layout-v1-before-state-v1')).length),18)
  let f=await visit('routing-list')
  await page.getByRole('button',{name:'交互预览',exact:true}).click()
  const rows=()=>f.locator('.routing-summary')
  const firstPriority=()=>f.locator('.routing-priority').first().innerText()
  const next=()=>f.locator('.routing-pagination button').last().click()
  assert.equal(await rows().count(),5);assert.equal(await firstPriority(),'1')
  await next();assert.equal(await firstPriority(),'6')
  await f.locator('.mobile-navigation button').filter({hasText:'设置'}).click()
  await f.locator('.desk[data-ui-page=settings]').waitFor()
  await f.locator('.mobile-navigation button').filter({hasText:'分流'}).click()
  await f.locator('.routing-summary').first().waitFor();assert.equal(await firstPriority(),'6')
  await f.getByRole('searchbox',{name:'搜索规则或出口',exact:true}).fill('service-24')
  assert.equal(await rows().count(),1);assert.equal(await firstPriority(),'24')
  await f.getByRole('searchbox',{name:'搜索规则或出口',exact:true}).fill('')
  assert.equal(await rows().count(),5);assert.equal(await firstPriority(),'1')
  await f.getByRole('combobox',{name:'每页规则',exact:true}).selectOption('10')
  assert.equal(await rows().count(),10);await next();assert.equal(await firstPriority(),'11')
  await f.getByRole('combobox',{name:'每页规则',exact:true}).selectOption('20')
  assert.equal(await rows().count(),20);await next();assert.equal(await rows().count(),4);assert.equal(await firstPriority(),'21')
  await f.getByRole('combobox',{name:'每页规则',exact:true}).selectOption('5')
  await f.getByRole('button',{name:'下移规则 5',exact:true}).click()
  assert.equal(await firstPriority(),'6');assert.ok((await rows().first().innerText()).includes('service-5'))
  await f.getByRole('button',{name:'编辑规则 6',exact:true}).click()
  await f.locator('.routing-editor input[autofocus]').fill('edited.example.invalid')
  await f.getByRole('button',{name:'完成编辑',exact:true}).click()
  await f.locator('body').evaluate(()=>{
   const original=window.fetch;window.routePayloads=[]
   window.fetch=async(input,init)=>{const url=new URL(typeof input==='string'?input:input.url,location.href);if(url.pathname==='/api/android/routing'&&init?.method==='PUT'){
    const body=JSON.parse(init.body);window.routePayloads.push(body)
    if(window.routePayloads.length===1)return Response.json({detail:'示例保存失败'},{status:503})
    return Response.json({revision:body.revision+1,rules:body.rules,targets:['DIRECT','REJECT','自动选择']})
   }return original(input,init)}
  })
  await f.getByRole('button',{name:'保存规则',exact:true}).click()
  await f.getByRole('button',{name:'重试保存',exact:true}).waitFor()
  assert.equal(await rows().count(),5)
  await f.getByRole('button',{name:'重试保存',exact:true}).click()
  await f.locator('.routing-save-bar strong').filter({hasText:'规则已保存'}).waitFor()
  const payloads=await f.locator('body').evaluate(()=>window.routePayloads)
  assert.equal(payloads.length,2);assert.equal(payloads[1].rules.length,24)
  assert.equal(payloads[1].rules[5].value,'edited.example.invalid')
  assert.equal(payloads[1].rules[4].value,'com.example.app5')
  for(let i=0;i<3;i++)await next()
  assert.equal(await rows().count(),4)
  for(let i=0;i<4;i++)await rows().first().locator('.routing-summary-actions button.danger').click()
  assert.equal(await rows().count(),5);assert.equal(await firstPriority(),'16')
  await page.locator('.lab-context-canvas').screenshot({path:'test-output/android-routing-pagination.png'})
  for(const scene of ['空列表','加载中','读取失败','大量规则']){
   f=await visit('routing-list',scene)
   if(scene==='大量规则'){assert.equal(await f.locator('.routing-summary').count(),5);assert.ok((await f.locator('.routing-pagination').innerText()).includes('48'))}
   else assert.equal(await f.locator('.routing-summary').count(),0)
   assert.ok(await f.locator('.android-routing').evaluate(e=>e.offsetHeight<2000))
   states.push(scene)
  }
  f=await visit('settings-language','英文')
  assert.equal(await f.locator('.shell-brand').isVisible(),false)
  assert.ok(await f.locator('.language-settings').evaluate(e=>e.scrollHeight<=e.clientHeight))
  const scrollbar=await f.locator('.desk-content').evaluate(e=>({width:getComputedStyle(e,'::-webkit-scrollbar').width,radius:getComputedStyle(e,'::-webkit-scrollbar-thumb').borderRadius}))
  assert.equal(scrollbar.width,'7px');assert.equal(scrollbar.radius,'99px')
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[])
  const report={adoptedRules:18,states,pageSizes:[5,10,20],filterAcrossPages:true,pagePersistence:true,crossPageReorder:true,fullSavePayload:24,failedSaveRetry:true,lastPageClamp:true,scrollbar,errors,requests}
  fs.writeFileSync('test-output/android-states-pagination-verification.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report))
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
